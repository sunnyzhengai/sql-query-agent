	AND FM.FLO_MEAS_ID = '9001125002'	-- R HS ED SEPSIS CLINICAL_ALERTS CANCELLED

	AND FM.RECORDED_TIME IS NOT NULL 

	AND FM.RECORDED_TIME BETWEEN C.ADT_ARRIVAL_TIME AND C.ED_DEPARTURE_TIME

	AND FM.MEAS_VALUE IS NOT NULL

;







