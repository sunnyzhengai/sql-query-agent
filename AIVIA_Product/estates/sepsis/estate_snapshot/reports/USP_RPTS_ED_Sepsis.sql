	B.ENCOUNTER_ID, C.RECORD_NAME AS [EVENT], EEI.EVENT_TYPE AS [EVENT ID],EEI.EVENT_TIME,

	ROW_NUMBER() OVER(PARTITION BY B.ENCOUNTER_ID ORDER BY EEI.EVENT_TIME ) AS TIME_LINE,

	ROW_NUMBER() OVER(PARTITION BY B.ENCOUNTER_ID, EEI.EVENT_TYPe ORDER BY EEI.EVENT_TIME ) AS REQ_LINE--JUST IN CASE IF THERE IS MORE THAN ONE EVENT OF THE SAME EVENT_TYPE.

INTO #BedEvents

FROM #Base_Pop B

	INNER JOIN [dbo].ED_PATIENT_INFO EPI ON EPI.ENCOUNTER_ID = B.ENCOUNTER_ID

	INNER JOIN [dbo].ED_EVENT_INFO EEI ON EEI.EVENT_ID = EPI.EVENT_ID AND EEI.EVENT_TYPE IN ('2600000347','2600000346')

	INNER JOIN [dbo].ED_EVENT_TEMPLATES C ON EEI.EVENT_TYPE = C.RECORD_ID

