/* SV02                */

/* ******************* */

DROP TABLE IF EXISTS #SVO2;



SELECT

	B.ENCOUNTER_ID

	, PO.ORDER_TIME AS MBOrderTime

	, LAB_ORDER_RESULTS.RESULT_TIME

	, LAB_ORDER_RESULTS.COMP_OBS_INST_TM AS CollectionTime

	, LAB_ORDER_RESULTS.ORD_VALUE

	, ROW_NUMBER() OVER(PARTITION BY B.ENCOUNTER_ID ORDER BY PO.ORDER_TIME ASC) AS TIME_LINE

	, LAB_ORDER_RESULTS.ORDER_PROC_ID

INTO #SVO2

FROM #Base_Pop B

	INNER JOIN [dbo].LAB_ORDER_RESULTS ON B.ENCOUNTER_ID = LAB_ORDER_RESULTS.ENCOUNTER_ID

	INNER JOIN [dbo].PROCEDURE_ORDERS PO ON PO.ORDER_PROC_ID = LAB_ORDER_RESULTS.ORDER_PROC_ID

