					OR

				  DATEDIFF(MINUTE, [BasePop].ADT_ARRIVAL_TIME, [#Pressors].TAKEN_TIME) <= 6*60

				)

			AND DATEDIFF(MINUTE, [BasePop].ADT_ARRIVAL_TIME, [bcx_order01].[Blood Culture First Order Time]) <= 72*60



		THEN 'Potential Septic Shock' 

		--ELSE 99	-- "Un-treated"

	  END AS [Septic Shock]



