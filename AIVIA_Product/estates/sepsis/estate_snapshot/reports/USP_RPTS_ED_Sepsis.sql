/* Order Set OSQ */

/* ************* */

DROP TABLE IF EXISTS #SSOrderSetOSQ_PRL;



	SELECT

		B.ENCOUNTER_ID

		, MO.ORDER_DTTM

		, MO2.ORD_OSQ_ID AS PRL_ORDERSET_ID

	INTO #SSOrderSetOSQ_PRL

	FROM #Base_Pop B

		INNER JOIN dbo.ORDER_TRACKING_METRICS MO ON MO.ENCOUNTER_ID = B.ENCOUNTER_ID

		INNER JOIN [dbo].MEDICATION_ORDERS_EXT MO2 ON MO2.ORDER_ID = MO.ORDER_ID AND MO2.ORD_OSQ_ID IN (400002,400007,400003,400004)

	WHERE MO.ORDER_DTTM BETWEEN B.ADT_ARRIVAL_TIME AND B.ED_DEPARTURE_TIME



UNION



	SELECT

		B.ENCOUNTER_ID

		, MO.ORDER_DTTM

		, MO2.ORD_OSQ_ID AS PRL_ORDERSET_ID

	FROM #Base_Pop B

		INNER JOIN dbo.ORDER_TRACKING_METRICS MO ON MO.ENCOUNTER_ID = B.ENCOUNTER_ID

		INNER JOIN [dbo].PROCEDURE_ORDERS_EXT MO2 ON MO2.ORDER_ID = MO.ORDER_ID AND MO2.ORD_OSQ_ID IN (400002,400007,400003,400004)

	WHERE

		MO.ORDER_DTTM BETWEEN B.ADT_ARRIVAL_TIME AND B.ED_DEPARTURE_TIME



UNION



	SELECT

		B.ENCOUNTER_ID

		, MO.ORDER_DTTM

		, MO.PRL_ORDERSET_ID

	FROM #Base_Pop B

		INNER JOIN dbo.ORDER_TRACKING_METRICS MO ON MO.ENCOUNTER_ID = B.ENCOUNTER_ID

	WHERE

		MO.PRL_ORDERSET_ID IN (400001)-- (40400100, 40400058, 40400196, 40400153, 4058600002, 400001) --Severe Sepsis, Short Stay – Sepsis, H/O – Sepsis CLINICAL_ALERTS, ID – Staph Aureus Sepsis, H/O Sepsis CLINICAL_ALERTS in Clinic, Sepsis Pathway

		AND MO.ORDER_DTTM BETWEEN B.ADT_ARRIVAL_TIME AND B.ED_DEPARTURE_TIME

;





