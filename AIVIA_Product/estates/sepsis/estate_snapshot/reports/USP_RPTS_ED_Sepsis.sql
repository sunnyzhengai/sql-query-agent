					OR

				  [#Pressors].TAKEN_TIME IS NOT NULL

				)



		THEN 'Septic Shock'

		

		WHEN DATEDIFF(MINUTE, [BasePop].ADT_ARRIVAL_TIME, [ABX1].ABX_ADMIN_TIME) <= 6*60

			AND DATEDIFF(MINUTE, [BasePop].ADT_ARRIVAL_TIME, [BPB1].BOLUS_ADMIN_TIME) <= 6*60

