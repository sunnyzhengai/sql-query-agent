/* Bolus               */

/* ******************* */

DROP TABLE IF EXISTS #BasePopBolus;



SELECT

	B.ENCOUNTER_ID

	, MA.TAKEN_TIME AS BOLUS_ADMIN_TIME

	, CASE	WHEN MO.MEDICATION_ID IN (700001, 700002) THEN 'SODIUM CHLORIDE 0.99%'

			ELSE MEDS.[NAME]

	  END AS Medication

	, ROW_NUMBER() OVER(PARTITION BY B.ENCOUNTER_ID ORDER BY MA.TAKEN_TIME ASC) TIME_LINE

	, MA.SIG AS BOLUS_VOLUME



INTO #BasePopBolus 

FROM #Base_Pop B

	INNER JOIN dbo.MEDICATION_ORDERS MO ON MO.ENCOUNTER_ID = B.ENCOUNTER_ID

	INNER JOIN dbo.MEDICATIONS MEDS ON MEDS.MEDICATION_ID = MO.MEDICATION_ID

	INNER JOIN dbo.MED_ADMIN_RECORDS MA ON MA.ORDER_MED_ID = MO.ORDER_MED_ID



WHERE 1=1

	AND MA.TAKEN_TIME IS NOT NULL --ADMINISTERED BOLUS ONLY

	AND MA.TAKEN_TIME BETWEEN B.ADT_ARRIVAL_TIME AND B.ED_DEPARTURE_TIME

	AND (MO.MEDICATION_ID IN (700001  --SODIUM CHLORIDE 0.99 % IV BOLUS

							, 7000739 --LACTATED RINGERS IV BOLUS

							, 700003    --ALBUMIN, HUMAN 95 % INTRAVENOUS SOLUTION

							, 7006331 --ELECTROLYE-A IV Bolus (PLASMALYTE)

							, 700002	--SODIUM CHLORIDE 0.99 % INJECTION SYRINGE--ADDED ON 04.02.2019

							)

		OR (MO.MEDICATION_ID = 700004)

	AND MO.HV_DISCR_FREQ_ID = '300902') -- FREQUENCY = ONCE 

	AND MA.MAR_ACTION_CODE IN ('1'			--GIVEN

							, '7'			--RESTARTED

							, '102'		--GIVEN BY OTHER

							, '105'		--NEW CARTRIDGE

							, '113'		--GIVEN DURING DOWNTIME

							, '114'		--STARTED DURING DOWNTIME

							, '115'		--MEDICATION APPLIED

							, '122'		--CONTINUED FROM OR

							, '124'		--SELF ADMINISTERED VIA PUMP

							, '132'		--CONTINUED FROM PREVIOUS ORDER

							, '143'		--REDOSE

							, '1604'		--INFUSION GREATER THAN 15 MIN

							, '1605'		--INFUSION LESS THAN 15 MIN

							, '1607'		--NEW CARTRIDGE

							, '6'			--NEW BAG

							)

	AND CONVERT(NUMERIC, MA.SIG ) > 95.0

GROUP BY

	B.ENCOUNTER_ID

	, MA.TAKEN_TIME

	, MA.SIG

	, MO.MEDICATION_ID

	, MEDS.NAME

	--select * from #BasePopBolus WHERE TIME_LINE=1

	/*PATIENTS Weight*/

;





/* ******************* */

/* Encounter Weight    */

/* ******************* */

DROP TABLE IF EXISTS #EncounterWeights;



SELECT

	A.ENCOUNTER_ID

	, CAST(ROUND(CONVERT(FLOAT, MEAS_VALUE) * 0.0283495, 2) AS DECIMAL(4, 1)) AS EncWeight

	, ROW_NUMBER() OVER(PARTITION BY A.ENCOUNTER_ID ORDER BY C.RECORDED_TIME ASC) AS TIME_LINE

INTO #EncounterWeights

FROM #Base_Pop A

	INNER JOIN [dbo].FLOWSHEET_RECORDS B ON A.INPATIENT_DATA_ID = B.INPATIENT_DATA_ID

	INNER JOIN [dbo].FLOWSHEET_MEASUREMENTS C ON B.FSD_ID = C.FSD_ID AND  C.FLO_MEAS_ID='94'

;





/* ******************* */

/* Hypotension         */

/* ******************* */

DROP TABLE IF EXISTS #Hypotension;



SELECT

	C.ENCOUNTER_ID

	, FM.RECORDED_TIME

	, C.AGE_MONTHS

	, C.AGE_YEARS

	, LEFT(FM.MEAS_VALUE, CHARINDEX('/', FM.MEAS_VALUE)-1) AS SYSTOLIC

	, FM.MEAS_VALUE

	, ROW_NUMBER() OVER(PARTITION BY C.ENCOUNTER_ID ORDER BY FM.RECORDED_TIME ASC) AS TIME_LINE

INTO #Hypotension 

FROM #Base_Pop C 

	INNER JOIN [dbo].FLOWSHEET_RECORDS FR ON FR.INPATIENT_DATA_ID = C.INPATIENT_DATA_ID

	INNER JOIN [dbo].FLOWSHEET_MEASUREMENTS FM ON FM.FSD_ID = FR.FSD_ID

WHERE 1=1

	AND FM.FLO_MEAS_ID = '95'

	AND FM.RECORDED_TIME IS NOT NULL 

	AND FM.RECORDED_TIME BETWEEN C.ADT_ARRIVAL_TIME AND C.ED_DEPARTURE_TIME

	AND FM.MEAS_VALUE IS NOT NULL

;







/* ********************** */

/* Sepsis CLINICAL_ALERTS Cancelled */

/* ********************** */

DROP TABLE IF EXISTS #SepsisAlertCancelled;



SELECT 

	C.ENCOUNTER_ID

	, FM.RECORDED_TIME	AS SEPSIS_ALERT_CANC_TIME

	, C.AGE_MONTHS

	, C.AGE_YEARS

	, 'Y'				AS SEPSIS_ALERT_CANC_FLAG

	, FM.MEAS_COMMENT	AS SEPSIS_ALERT_CANC_BY		-- Free text

	, ROW_NUMBER() OVER(PARTITION BY C.ENCOUNTER_ID ORDER BY FM.RECORDED_TIME ASC) AS TIME_LINE

INTO #SepsisAlertCancelled 

FROM #Base_Pop C 

	INNER JOIN [dbo].FLOWSHEET_RECORDS FR ON FR.INPATIENT_DATA_ID = C.INPATIENT_DATA_ID

	INNER JOIN [dbo].FLOWSHEET_MEASUREMENTS FM ON FM.FSD_ID = FR.FSD_ID

