IF @StartDate IS NULL SET @StartDate = '2026-01-01';

SELECT E.ENCOUNTER_ID, E.PATIENT_ID
INTO #Recent
FROM dbo.ENCOUNTER E
WHERE E.VISIT_DATE >= @StartDate
  AND E.APPT_STATUS_C = 2;

SELECT R.PATIENT_ID, D.DX_CODE
FROM #Recent R
JOIN dbo.ENCOUNTER_DX D ON D.ENCOUNTER_ID = R.ENCOUNTER_ID
WHERE D.DX_CODE LIKE 'E11%';
