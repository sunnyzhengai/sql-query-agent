CREATE PROCEDURE reporting.USP_Panel_ED_Visits
AS
BEGIN
WITH
Base_Cohort AS (
  SELECT DISTINCT E.PATIENT_ID
  FROM ENCOUNTERS E
  JOIN ENCOUNTER_DIAGNOSIS ED ON ED.ENCOUNTER_ID = E.ENCOUNTER_ID
  JOIN DIAGNOSIS_CODESET DC ON DC.DX_CODE = ED.DX_CODE
  WHERE ED.DX_CODE LIKE 'E11%'
),
ED_Symptom_Visits AS (
  SELECT BC.PATIENT_ID
  FROM Base_Cohort BC
  JOIN HOSPITAL_ENCOUNTERS HE ON HE.PATIENT_ID = BC.PATIENT_ID
  JOIN HOSPITAL_DIAGNOSIS HD ON HD.HOSP_ENC_ID = HE.HOSP_ENC_ID
  WHERE HE.ENCOUNTER_TYPE = 'ED' AND HD.DX_CODE LIKE 'R73%'
)
SELECT * FROM ED_Symptom_Visits;
END
