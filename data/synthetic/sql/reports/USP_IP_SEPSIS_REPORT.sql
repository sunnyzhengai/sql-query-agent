SELECT

	OM.PAT_ENC_CSN_ID

	, B.ADT_DEPARTMENT_ID

	, B.ADT_DEPARTMENT_NAME

	, B.IN_DTTM

	, B.OUT_DTTM

	, CM.NAME

	, MAI.TAKEN_TIME AS ABX_ADMIN_TIME

	, MAI.SIG AS BOLUS_VOLUME

	, ROW_NUMBER() OVER(PARTITION BY OM.PAT_ENC_CSN_ID ORDER BY MAI.TAKEN_TIME) TIME_LINE

